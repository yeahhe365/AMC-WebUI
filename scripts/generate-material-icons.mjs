const ICONS_JSON_PATH = 'node_modules/@iconify-json/material-icon-theme/icons.json';
const OUTPUT_PATH = 'src/components/message/code/materialIcons.generated.ts';

const HEADER = '// AUTO-GENERATED by scripts/generate-material-icons.mjs — do not edit. Run "npm run generate:icons".';

const cwd = process.cwd();
const packageJsonPath = join(cwd, 'package.json');
if (!exists(packageJsonPath)) {
  throw new Error(
    `Not the project root: no package.json at ${packageJsonPath}. Run from /Volumes/WD_BLACK/Code/AMC-WebUI`,
  );
}

const iconsJsonPath = resolve(cwd, ICONS_JSON_PATH);
if (!exists(iconsJsonPath)) {
  throw new Error(
    `Missing ${ICONS_JSON_PATH}. Run "npm install" first (devDependency @iconify-json/material-icon-theme).`,
  );
}

const collection = JSON.parse(readFileSync(iconsJsonPath, 'utf8'));
const { icons, aliases = {} } = collection;

const resolveIcon = (name) => {
  const entry = icons[name] ?? icons[aliases[name]];
  if (!entry) {
    throw new Error(`Icon "${name}" not found in ${ICONS_JSON_PATH}. Check the name or update the package.`);
  }
  return entry;
};

const entries = Object.fromEntries(
  [...ICON_NAMES].sort().map((name) => {
    const icon = resolveIcon(name);
    return [
      name,
      {
        body: icon.body,
        width: icon.width ?? 24,
        height: icon.height ?? 24,
      },
    ];
  }),
);

const recordLines = Object.entries(entries)
  .map(([name, { body, width, height }]) => {
    const bodyJson = JSON.stringify(body);
    return `  ${JSON.stringify(name)}: { body: ${bodyJson}, width: ${width}, height: ${height} },`;
  })
  .join('\n');

const raw = `${HEADER}
type MaterialIconData = { body: string; width: number; height: number };

export const MATERIAL_ICONS: Readonly<Record<string, MaterialIconData>> = {
${recordLines}
};
`;

const resolvedConfig = await resolveConfig(cwd, { config: '.prettierrc' });
const output = await format(raw, { filepath: OUTPUT_PATH, ...resolvedConfig });
const outPath = resolve(cwd, OUTPUT_PATH);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output);

const totalBytes = Buffer.byteLength(output);
const bodyBytes = Object.values(entries).reduce((sum, { body }) => sum + Buffer.byteLength(body), 0);
console.log(`Wrote ${outPath}`);
console.log(`  ${Object.keys(entries).length} icons, raw body ${bodyBytes} bytes, file ${totalBytes} bytes`);

function exists(path) {
  try {
    readFileSync(path);
    return true;
  } catch {
    return false;
  }
}
